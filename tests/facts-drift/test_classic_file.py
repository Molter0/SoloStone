"""The Classic format's card file (facts/classic-2014.json, docs/classic-2014.md) is well formed.

It is generated by tools/gen_classic_facts.py from hsdata's 37.0.0.254477 CardDefs.xml, which CI does not have, so this
checks the file's own shape and what it says about the Violet Hold file. The engine proof (ClassicFormatProof) checks
how the rows load and play. Run through tests/run.py (suite facts-drift).
"""
import hashlib
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PINNED = 'de717fc210614be2033152cffae6052fb1cd6b85812dc598218ce75263ca9df3'
VANILLA = 1646


def tags(row):
    return dict(row['tags'])


class ClassicFileTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.doc = json.loads((ROOT / 'facts' / 'classic-2014.json').read_text(encoding='utf-8'))
        cls.rows = cls.doc['overlay']['cards']
        base = json.loads((ROOT / 'facts' / 'violet-hold-2026-09.json').read_text(encoding='utf-8'))
        cls.base = {row['id']: row for row in base['cards']}
        cls.base.update({row['id']: row for row in base['overlay']['cards'] if not row.get('snapshot')})
        cls.base_dbfs = {row['dbf'] for row in base['cards'] + base['overlay']['cards']}

    def test_header(self):
        self.assertEqual(set(self.doc), {'schemaVersion', 'meta', 'cards', 'overlay'})
        self.assertEqual((self.doc['schemaVersion'], self.doc['meta'], self.doc['cards']), (1, 'classic-2014', []))
        overlay = self.doc['overlay']
        self.assertEqual((overlay['schemaVersion'], overlay['sourceBuild'], overlay['exportSha256']), (1, '37.0.0.254477', PINNED))

    def test_rows(self):
        ids = [row['id'] for row in self.rows]
        self.assertEqual(ids, sorted(ids), 'rows are sorted by id')
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(len({row['dbf'] for row in self.rows}), len(self.rows))
        for row in self.rows:
            t = tags(row)
            self.assertTrue(row['id'].startswith('VAN_') and 'puzzle' not in row['id'].lower(), row['id'])
            self.assertEqual(t.get(183), VANILLA, row['id'])
            self.assertIn(321, t, row['id'] + ' carries its collectible tag')
            self.assertIn(202, t, row['id'])
            self.assertNotIn(row['id'], self.base, row['id'] + ' would collide with a Violet Hold row')
            self.assertNotIn(row['dbf'], self.base_dbfs, row['id'] + ' dbf collides with a Violet Hold row')
            self.assertEqual(row['textHash'], hashlib.sha256(row['text'].encode('utf-8')).hexdigest()[:16], row['id'])
            if t[202] == 7:
                self.assertIn(187, t, row['id'] + ' weapon durability is tag 187')
                self.assertNotIn(45, t, row['id'])

    def test_originals(self):
        for row in self.rows:
            if 'originalId' not in row:
                continue
            original = self.base.get(row['originalId'])
            self.assertIsNotNone(original, row['id'] + ' original exists')
            self.assertEqual(original['dbf'], row['originalDbf'], row['id'])
            if 192 in tags(row) and 192 in tags(original):
                self.assertEqual(tags(row)[192], tags(original)[192], row['id'] + ' Spell Damage amount from the original')

    def test_collectible_set(self):
        collectible = [row for row in self.rows if tags(row).get(321) == 1]
        # 382 with VAN_EX1_572 Ysera, which the Violet Hold file already holds.
        self.assertEqual(len(collectible), 381)
        self.assertIn('VAN_EX1_572', self.base)
        self.assertTrue(all('originalId' in row for row in collectible))
        self.assertEqual({tags(row)[202] for row in collectible}, {4, 5, 7})


if __name__ == '__main__':
    unittest.main()
